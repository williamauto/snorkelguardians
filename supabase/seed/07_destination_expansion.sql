-- Destination expansion: South Florida, the Florida Keys, Lauderdale-by-the-Sea,
-- Florida Springs, plus the missing Hawaii, San Diego and Catalina spots.
--
-- Hierarchy after this seed:
--   florida
--     |- florida-springs          (area)
--     |- south-florida             (area)
--          |- miami                (city)   <- re-parented below
--          |- lauderdale-by-the-sea (city)
--          |- florida-keys         (city)
--
-- The site walks regions recursively, so florida/florida-springs and
-- florida/south-florida still surface every spot beneath them.

-- ---------- new regions ----------
-- The url path is set explicitly rather than derived from the parent, so the
-- new destinations keep short, readable urls (/florida/lauderdale-by-the-sea/)
-- while the parent chain still gives the hierarchy for breadcrumbs.
